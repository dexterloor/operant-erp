    /**
     * @param array<mixed> $a
     *
     * @return array<mixed>
     */
    private static function sortedKeys(array $a): array
    {
        $out = ['type' => $a['type'] ?? null];
        foreach ($a as $k => $v) {
            if ('type' !== $k) {
                $out[$k] = $v;
            }
        }

        return $out;
    }

    /**
     * @param array<mixed> $a
     *
     * @return array<mixed>
     */
    private static function canonical(array $a): array
    {
        if (!array_is_list($a)) {
            ksort($a);
        }
        foreach ($a as $k => $v) {
            if (\is_array($v)) {
                $a[$k] = self::canonical($v);
            }
        }

        return $a;
    }

