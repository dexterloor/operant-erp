    public function noWriteSchemaDeclaresAnIdProperty(): void
    {
        $spec = $this->regenerate();
        $writes = $this->writeOperations($spec);

        self::assertNotSame([], $writes, 'No write operation was found, so the assertion below would be vacuous.');

        $inspected = 0;
        $offenders = [];

        foreach ($writes as $label => $operation) {
            foreach ($operation['requestBody']['content'] ?? [] as $mediaType => $content) {
                if (!isset($content['schema'])) {
                    continue;
                }

                ++$inspected;
                foreach ($this->propertyPaths($content['schema'], $spec) as $path) {
                    if (str_ends_with($path, '/id')) {
                        $offenders[] = $label.' '.$mediaType.' '.$path;
                    }
                }
            }
        }

        self::assertGreaterThan(0, $inspected, 'No request schema was inspected, so this check had no subject.');
        self::assertSame([], $offenders, 'B-3: a write schema declares a row identifier.');
    }

