                    $typed = false;
                    foreach ($property->getAttributes(ApiProperty::class) as $attribute) {
                        $typed = $typed || isset($attribute->newInstance()->getSchema()['type']);
                    }
                    if (!$typed) {
                        $untyped[$key] = true;
                    }
                }
            }
        }

