    private static function pathParametersInTheSpec(array $spec): array
    {
        $out = [];
        foreach (GeneratedSpec::operations($spec) as $data) {
            foreach ($data['operation']['parameters'] ?? [] as $parameter) {
                if ('path' !== ($parameter['in'] ?? null)) {
                    continue;
