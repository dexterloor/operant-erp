        sort($untyped);
        $expected = self::MIXED_INPUTS_NOT_YET_TYPED;
        sort($expected);
        self::assertSame($expected, $untyped, 'A `public mixed` request field is served as string|null. Declare #[ApiProperty(schema: [...])] on it.');
    }
