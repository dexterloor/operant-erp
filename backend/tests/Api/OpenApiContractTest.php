    /**
     * @param array<string, mixed> $spec
     *
     * @return array<string, array<string, mixed>>
     */
    private function writeOperations(array $spec): array
    {
        $writes = [];

        foreach ($spec['paths'] as $path => $methods) {
            foreach ($methods as $method => $operation) {
                if (\in_array(strtoupper((string) $method), self::WRITE_METHODS, true)) {
                    $writes[strtoupper((string) $method).' '.$path] = $operation;
                }
            }
        }

        return $writes;
    }

    /**
     * @param array<string, mixed> $schema
     * @param array<string, mixed> $spec
     *
     * @return array<string, mixed>
     */
    private function resolve(array $schema, array $spec): array
    {
        if (isset($schema['$ref']) && \is_string($schema['$ref'])) {
            $name = substr($schema['$ref'], 21);

            return $spec['components']['schemas'][$name] ?? [];
        }

        return $schema;
    }

    /**
     * Every property path a schema declares, with `$ref`s followed.
     *
     * @param array<string, mixed> $schema
     * @param array<string, mixed> $spec
     * @param list<string>         $seen
     *
     * @return list<string>
     */
    private function propertyPaths(array $schema, array $spec, string $prefix = '', array $seen = []): array
    {
        if (isset($schema['$ref']) && \is_string($schema['$ref'])) {
            if (\in_array($schema['$ref'], $seen, true)) {
                return [];
            }
            $seen[] = $schema['$ref'];
        }

        $schema = $this->resolve($schema, $spec);
        $paths = [];

        foreach ($schema['properties'] ?? [] as $name => $property) {
            $here = $prefix.'/'.$name;
            $paths[] = $here;
            if (\is_array($property)) {
                $paths = [...$paths, ...$this->propertyPaths($property, $spec, $here, $seen)];
            }
        }

        foreach (['items', 'additionalProperties'] as $nested) {
            if (\is_array($schema[$nested] ?? null)) {
                $paths = [...$paths, ...$this->propertyPaths($schema[$nested], $spec, $prefix.'/[]', $seen)];
            }
        }

        foreach (['anyOf', 'oneOf', 'allOf'] as $composite) {
            foreach ($schema[$composite] ?? [] as $branch) {
                if (\is_array($branch)) {
                    $paths = [...$paths, ...$this->propertyPaths($branch, $spec, $prefix, $seen)];
                }
            }
        }

        return $paths;
    }

